import type { UnifiedGrant } from "../../grants";

function programDirectory(
  id: string,
  title: string,
  funderName: string,
  url: string,
  demographicSetAsides: UnifiedGrant["demographicSetAsides"],
  funderType: UnifiedGrant["funderType"] = "nonprofit",
): UnifiedGrant {
  return {
    id,
    directoryOnly: true,
    status: "unknown",
    grantTier: "Foundation",
    poolTier: "corporate_diversity",
    title,
    funderName,
    funderType,
    awardFloor: 0,
    awardCeiling: 0,
    deadline: "Check official portal for current programs",
    isRolling: false,
    costSharingRequired: false,
    eligibleEntityTypes: ["for_profit", "nonprofit_501c3", "individual"],
    demographicSetAsides,
    geographicScope: { level: "national" },
    applicationMethod: "online_portal",
    directApplyUrl: url,
    isFreeToApply: true,
    summaryText: `${title} is a research directory. Confirm current opportunities, eligibility, deadlines, and application requirements with the official organization.`,
  };
}

